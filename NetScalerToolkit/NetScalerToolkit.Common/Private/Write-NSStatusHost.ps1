function Write-NSStatusHost {
    <#
    .SYNOPSIS
        Writes status text to the host.

    .DESCRIPTION
        The single place status output reaches the console. Write-Host targets the information
        stream, so the success stream of the calling command stays clean. Color is left out when
        the NO_COLOR environment variable was set at initialization.

    .PARAMETER Text
        Text to write.

    .PARAMETER Color
        Foreground color.

    .PARAMETER NoNewline
        Keeps the cursor on the current line.

    .EXAMPLE
        Write-NSStatusHost -Text '[  OK  ]' -Color Green

    .NOTES
        Function  : Write-NSStatusHost
        Author    : John Billekens
        Copyright : Copyright (c) John Billekens Consultancy
        Version   : 2026.1103.2230
    #>
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSAvoidUsingWriteHost', '', Justification = 'Status output is console decoration and must stay off the success stream.')]
    [CmdletBinding()]
    param(
        [AllowEmptyString()]
        [String]$Text,

        [String]$Color,

        [Switch]$NoNewline
    )

    $hostParams = @{
        Object    = $Text
        NoNewline = $NoNewline.IsPresent
    }
    if (-not [string]::IsNullOrEmpty($Color) -and -not $script:NSStatus.NoColor) {
        $hostParams.ForegroundColor = $Color
    }
    Write-Host @hostParams
}

