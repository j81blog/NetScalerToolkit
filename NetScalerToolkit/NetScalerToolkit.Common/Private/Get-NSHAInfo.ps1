function Get-NSHAInfo {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [psobject] $Session
    )

    $nsconfigResponse = Invoke-NSRestRequest -Session $Session -Method GET -Task config -Type nsconfig -RawResponse
    $hanodeResponse = Invoke-NSRestRequest -Session $Session -Method GET -Task config -Type hanode -RawResponse

    $nsconfig = $nsconfigResponse.nsconfig
    if ($nsconfig -is [array]) {
        $nsconfig = $nsconfig[0]
    }

    $hanodes = @($hanodeResponse.hanode)
    $primaryNode = $hanodes | Where-Object { $_.state -eq 'Primary' } | Select-Object -First 1
    $secondaryNode = $hanodes | Where-Object { $_.state -eq 'Secondary' } | Select-Object -First 1
    $connectedNode = $hanodes | Where-Object { $_.ipaddress -eq $nsconfig.ipaddress } | Select-Object -First 1

    $primaryIP = $nsconfig.primaryip
    if (-not $primaryIP -and $primaryNode) {
        $primaryIP = $primaryNode.ipaddress
    }

    $secondaryIP = $null
    if ($secondaryNode) {
        $secondaryIP = $secondaryNode.ipaddress
    }

    $connectedNodeState = $null
    if ($connectedNode) {
        $connectedNodeState = $connectedNode.state
    }

    $isHA = $nsconfig.systemtype -eq 'HA'
    $isStandalone = $nsconfig.systemtype -like 'Stand-alone'
    $isConnectedToPrimary = $false

    if ($connectedNodeState -eq 'Primary' -or ($primaryIP -and $nsconfig.ipaddress -eq $primaryIP)) {
        $isConnectedToPrimary = $true
    }

    return [pscustomobject] @{
        IsHA = $isHA
        IsStandalone = $isStandalone
        SystemType = $nsconfig.systemtype
        ConnectedNodeIP = $nsconfig.ipaddress
        ConnectedNodeState = $connectedNodeState
        IsConnectedToPrimary = $isConnectedToPrimary
        IsConnectedToSecondary = ($connectedNodeState -eq 'Secondary')
        PrimaryIP = $primaryIP
        SecondaryIP = $secondaryIP
        PrimaryNode = $primaryNode
        SecondaryNode = $secondaryNode
        Nodes = $hanodes
        Nsconfig = $nsconfig
    }
}

