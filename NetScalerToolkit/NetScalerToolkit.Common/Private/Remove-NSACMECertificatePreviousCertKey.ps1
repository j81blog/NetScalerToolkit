function Remove-NSACMECertificatePreviousCertKey {
<#
    .SYNOPSIS
        Safely removes a previous NetScaler SSL certkey after certificate deployment.

    .DESCRIPTION
        Applies guardrails before deleting a previous certkey:
        - old and new certkey names must differ;
        - old certkey must exist;
        - old certkey must not be part of the new chain;
        - old certkey must not be globally VPN-bound.

    .PARAMETER Session
        Existing NetScaler session returned by Connect-NSNode.

    .PARAMETER OldCertKeyName
        Existing certkey name that may be removed.

    .PARAMETER NewCertKeyName
        Newly deployed certkey name.

    .PARAMETER NewChainCertKeyName
        Chain certkey names linked to the newly deployed certkey.

    .PARAMETER DeleteFromDevice
        Also remove the backing certificate/key file from the appliance.

    .NOTES
        Function  : Remove-NSACMECertificatePreviousCertKey
        Author    : John Billekens
        Copyright : Copyright (c) John Billekens Consultancy
        Version   : 2026.0605.2300
#>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [object]$Session,

        [string]$OldCertKeyName,

        [Parameter(Mandatory)]
        [string]$NewCertKeyName,

        [string[]]$NewChainCertKeyName = @(),

        [switch]$DeleteFromDevice
    )

    if ([string]::IsNullOrWhiteSpace($OldCertKeyName)) {
        return [PSCustomObject]@{ Status = 'Skipped'; Reason = 'Old certkey name not provided.' }
    }

    if ($OldCertKeyName -eq $NewCertKeyName) {
        return [PSCustomObject]@{ Status = 'Skipped'; Reason = 'Old and new certkey names are equal.' }
    }

    if (@($NewChainCertKeyName | Where-Object { $_ -eq $OldCertKeyName }).Count -gt 0) {
        return [PSCustomObject]@{ Status = 'Skipped'; Reason = 'Old certkey is part of the newly linked certificate chain.' }
    }

    $existing = Invoke-NSGetSSLCertKey -Session $Session -CertKey $OldCertKeyName -ReturnNullOnNotFound -ErrorAction Stop
    if (-not $existing) {
        return [PSCustomObject]@{ Status = 'Skipped'; Reason = 'Old certkey does not exist.' }
    }

    try {
        $vpnBindings = @(Invoke-NSGetVPNGlobalSSLCertKeyBinding -Session $Session -ReturnNullOnNotFound -ErrorAction Stop)
    } catch [System.Exception] {
        Write-NSACMECertificateLog Warning 'Deploy' "Could not inspect VPN global bindings for RemovePrevious safety check: $($_.Exception.Message)"
        return [PSCustomObject]@{ Status = 'Skipped'; Reason = 'Could not inspect VPN global bindings.' }
    }

    $isVpnBound = @(
        $vpnBindings | Where-Object {
            $_.certkeyname -eq $OldCertKeyName -or
            $_.cacert -eq $OldCertKeyName -or
            $_.userdataencryptionkey -eq $OldCertKeyName
        }
    ).Count -gt 0
    if ($isVpnBound) {
        return [PSCustomObject]@{ Status = 'Skipped'; Reason = 'Old certkey is globally VPN-bound.' }
    }

    Invoke-NSDeleteSSLCertKey -Session $Session -CertKey $OldCertKeyName -DeleteFromDevice:$DeleteFromDevice -Confirm:$false | Out-Null
    return [PSCustomObject]@{ Status = 'Deleted'; CertKeyName = $OldCertKeyName; DeleteFromDevice = [bool]$DeleteFromDevice }
}

